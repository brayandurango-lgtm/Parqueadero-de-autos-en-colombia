-- ============================================================================
-- Autos Colombia - Iteración 2, migración V2
-- Clientes del parqueadero y vínculo vehículo ↔ cliente
-- ----------------------------------------------------------------------------
-- Principios de esta migración:
--   1. Estrictamente aditiva: no reescribe V1 ni sus objetos, y solo añade
--      vehiculo.cliente_id a una tabla existente.
--   2. Compatible: los vehículos creados en la Iteración 1 quedan con
--      cliente_id NULL y siguen funcionando sin cliente vinculado.
--   3. Sin borrado en cascada: la FK es ON DELETE RESTRICT, para que un
--      cliente con historial no pueda desaparecer arrastrando vehículos.
--   4. Baja lógica, no borrado: el estado se lleva con cliente.activo.
--   5. Unicidad por (tipo_documento, documento): el mismo número con distinto
--      tipo de documento son dos personas distintas y sí se permiten.
-- ============================================================================

CREATE TABLE cliente (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    tipo_documento   VARCHAR(20)   NOT NULL,
    documento        VARCHAR(20)   NOT NULL,
    nombre_completo  VARCHAR(120)  NOT NULL,
    telefono         VARCHAR(20)   NOT NULL,
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cliente PRIMARY KEY (id),
    CONSTRAINT uk_cliente_tipo_documento UNIQUE (tipo_documento, documento),
    CONSTRAINT chk_cliente_tipo_documento CHECK (tipo_documento IN ('CC', 'CE', 'TI', 'PASAPORTE', 'OTRO'))
);

CREATE INDEX idx_cliente_documento      ON cliente (documento);
CREATE INDEX idx_cliente_nombre_completo ON cliente (nombre_completo);
CREATE INDEX idx_cliente_activo          ON cliente (activo);

COMMENT ON TABLE  cliente                    IS 'Titular o usuaria del servicio de parqueadero. No tiene credenciales ni rol de acceso.';
COMMENT ON COLUMN cliente.tipo_documento     IS 'Clasificación interna del documento (CC/CE/TI/PASAPORTE/OTRO). No es una validación oficial de identidad.';
COMMENT ON COLUMN cliente.documento          IS 'Documento normalizado: sin espacios exteriores, en mayúsculas con Locale.ROOT y conservando ceros iniciales. Nunca se almacena como número.';
COMMENT ON COLUMN cliente.activo             IS 'Baja lógica. Un cliente inactivo conserva sus vehículos y su historial, pero no admite vinculaciones nuevas.';

-- ---------------------------------------------------------------------------
-- Vínculo vehículo → cliente (nullable: la Iteración 1 no tenía clientes)
-- ---------------------------------------------------------------------------

ALTER TABLE vehiculo
    ADD COLUMN cliente_id BIGINT NULL;

ALTER TABLE vehiculo
    ADD CONSTRAINT fk_vehiculo_cliente
    FOREIGN KEY (cliente_id) REFERENCES cliente (id)
    ON DELETE RESTRICT;

CREATE INDEX idx_vehiculo_cliente ON vehiculo (cliente_id);

COMMENT ON COLUMN vehiculo.cliente_id IS 'Cliente titular actual. Si es NULL, el vehículo proviene de la Iteración 1 y su titularidad sigue en los campos propietario_*; la vinculación queda pendiente.';
COMMENT ON COLUMN vehiculo.propietario_documento IS 'Se conserva por compatibilidad. En vehículos ya vinculados el valor devuelto por la API se proyecta desde cliente, no desde esta columna.';
